/** The category as the visitor should read it; scores and ids never change. */
export function localizeCategory(category: Category, lang: Lang): Category {
  const t = lang === 'pt' ? pt[category.id] : undefined;
  if (!t) return category;
  return {
    ...category,
    label: t.label,
    description: t.description,
    questions: category.questions.map((q) => {
      const tq = t.questions[q.id];
      if (!tq) return q;
      const [text, ...answers] = tq;
      return { ...q, text, answers: q.answers.map((a, i) => ({ ...a, label: answers[i] ?? a.label })) };
    }),
  };
}
